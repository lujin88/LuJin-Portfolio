// Bundles content/ask-lu/*.md into lib/ask-lu-knowledge.generated.ts.
// Runs automatically before `dev` and `build` (see package.json scripts).
// TODO(Lu) placeholders are removed here, so unfinished notes never reach the model.

import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const ROOT = process.cwd();
const SRC = path.join(ROOT, "content", "ask-lu");
const OUT = path.join(ROOT, "app", "api", "ask-lu", "knowledge.generated.ts");
const SKIP = new Set(["README.md", "system-prompt.md"]);

async function listMarkdown(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const e of entries) {
    const full = path.join(dir, e.name);
    if (e.isDirectory()) files.push(...(await listMarkdown(full)));
    else if (e.name.endsWith(".md") && !SKIP.has(e.name)) files.push(full);
  }
  return files.sort();
}

function stripTodos(text) {
  let todoCount = 0;
  const lines = text
    // <!-- hidden --> blocks are drafts, never sent
    .replace(/<!--[\s\S]*?-->/g, "")
    // "(TODO(Lu): ...)" inside a sentence
    .replace(/\s*\(TODO\(Lu\):[^)]*\)/g, () => (todoCount++, ""))
    .split("\n")
    .map((line) => {
      const i = line.indexOf("TODO(Lu):");
      if (i === -1) return line;
      todoCount++;
      return line.slice(0, i).trimEnd();
    })
    // drop lines left empty or as a bare label ("- ", "Case study page:")
    .filter((line) => {
      const t = line.trim();
      return !(t === "-" || t === "*" || (t.endsWith(":") && t.length < 40));
    });
  return { text: lines.join("\n").replace(/\n{3,}/g, "\n\n").trim(), todoCount };
}

const systemPrompt = await readFile(path.join(SRC, "system-prompt.md"), "utf8");
const files = await listMarkdown(SRC);

let totalTodos = 0;
const sections = [];
for (const file of files) {
  const raw = await readFile(file, "utf8");
  const { text, todoCount } = stripTodos(raw);
  totalTodos += todoCount;
  sections.push(`<file name="${path.relative(SRC, file)}">\n${text}\n</file>`);
}

const full = `${systemPrompt.trim()}\n\n${sections.join("\n\n")}\n`;

await writeFile(
  OUT,
  `// AUTO-GENERATED by scripts/build-ask-lu.mjs — do not edit. Edit content/ask-lu/*.md instead.\n` +
    `export const ASK_LU_SYSTEM_PROMPT = ${JSON.stringify(full)};\n`
);

console.log(
  `[ask-lu] ${files.length} files, ~${Math.round(full.length / 4)} tokens, ${totalTodos} TODO(Lu) placeholders skipped`
);
